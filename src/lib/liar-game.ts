export const CATEGORY_NAMES = Object.keys(CATEGORIES);

export function isBuiltInCategory(category: string): boolean {
  return category in CATEGORIES;
}

export function pickWord(category: string): string {
  const words = CATEGORIES[category];
  if (!words || words.length === 0) throw new Error("알 수 없는 카테고리입니다.");
  return words[Math.floor(Math.random() * words.length)];
}

export function pickDifferentWord(category: string, exclude: string): string {
  const words = CATEGORIES[category]?.filter((w) => w !== exclude);
  if (!words || words.length === 0) throw new Error("같은 카테고리에서 다른 제시어를 찾을 수 없습니다.");
  return words[Math.floor(Math.random() * words.length)];
}

export function maxLiars(playerCount: number): number {
  return Math.max(1, Math.min(Math.floor(playerCount / 2), playerCount - 2));
}

export function pickRandomLiarIds(playerIds: string[], liarCount: number): string[] {
  const shuffled = [...playerIds];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  return shuffled.slice(0, liarCount);
}
